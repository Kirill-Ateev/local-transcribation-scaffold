"""Постобработка транскрипта Breeze-ASR-25: регекс-починка «capglue».

Fine-tune на мандарине перенёс привычку китайского письма (там нет пробелов
между словами) — на стыках предложений Breeze то пропускает точку с пробелом,
то саму точку, и конец одного предложения прилипает к началу следующего.
Capglue — рецепт из бенчмарка Егора Соколова «23 ASR-модели для русской
айтишной диктовки» (июнь 2026), там он даёт модели Breeze +1.4 Q и входит
в её конфиг-чемпион (promptv3 + capglue). Три правила поверх готового текста:

  1. строчная буква упёрлась в заглавную без пробела → вставить «. »
     (кулинариейПочему → кулинарией. Почему);
  2. точка без пробела перед заглавной буквой → вставить пробел
     (backup.Недавно → backup. Недавно);
  3. строчная кириллица в начале предложения после . ! ? → поднять регистр
     (кнопку. дальше я → кнопку. Дальше я).

Ограничения, важные для IT-диктовки:
- латиница→латиница после строчной НЕ считается склейкой: camelCase
  (useState, getUserData) остаётся целым;
- точка перед строчной не трогается: домены (example.com), расширения
  (app.py) и дроби (3.14) не повреждаются;
- многоточие «...» не считается концом предложения — регистр не поднимается;
- CJK-текст не затрагивается: у иероглифов нет регистра, а пунктуация
  полноширинная (。，), не ASCII.

Ограничение по замыслу: правило 1 вставляет именно «. » (склейка без пробела
у Breeze — это стык предложений). Известный ложный позитив правила 3 —
аббревиатуры вида «т.е. что-то»; в выводе Breeze они редки (модель пишет
слова целиком).
"""

from __future__ import annotations

import re

# Склейка «строчные + Заглавная кириллица» (оба слова кириллицей либо первое
# латиницей — camelCase не содержит кириллицы, ложных срабатываний нет).
_GLUE_INTO_CYR_UPPER = re.compile(r"([а-яё]+|[a-z]+)([А-ЯЁ])")

# Склейка «кириллическая строчная + CamelCase-латиница»: требуем заглавную
# плюс минимум две строчные, чтобы не задевать аббревиатуры (иCI, иоС).
_GLUE_INTO_LAT_UPPER = re.compile(r"([а-яё])([A-Z][a-z]{2,})")

# Точка без пробела перед заглавной буквой следующего слова.
_DOT_NO_SPACE = re.compile(r"\.(?=[А-ЯЁA-Z])")

# Строчная кириллица в начале предложения; lookbehind исключает «...».
_SENTENCE_LOWER = re.compile(r"(?<!\.)([.!?])(\s+)([а-яё])")


def apply_capglue(text: str) -> str:
    """Возвращает текст с починенными стыками предложений (идемпотентно)."""
    if not text:
        return text
    fixed = _GLUE_INTO_CYR_UPPER.sub(r"\1. \2", text)
    fixed = _GLUE_INTO_LAT_UPPER.sub(r"\1. \2", fixed)
    fixed = _DOT_NO_SPACE.sub(". ", fixed)
    fixed = _SENTENCE_LOWER.sub(
        lambda m: f"{m.group(1)}{m.group(2)}{m.group(3).upper()}", fixed
    )
    return fixed
